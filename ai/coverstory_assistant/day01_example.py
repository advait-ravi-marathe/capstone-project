"""Instructor-owned Python/JSON example used before the first learner task."""
from __future__ import annotations

import json


def example_request() -> dict[str, str]:
    # A Python dict is a convenient in-memory object. JSON is its portable text form.
    return {
        "instructions": "Use only the supplied synthetic policy excerpt. If unsupported, abstain.",
        "input": "Policy excerpt: Hail damage is excluded.\nQuestion: Is hail damage covered?",
    }


def example_model_output() -> dict[str, object]:
    # This is a fixed teaching fixture, not a model response or live-provider evidence.
    return {
        "answer": "No. The excerpt says hail damage is excluded.",
        "citations": [{"document_id": "SYN-POL-1", "section": "Exclusions"}],
        "abstained": False,
    }


def main() -> None:
    print("Request JSON:")
    print(json.dumps(example_request(), indent=2, ensure_ascii=False))
    print("Fixed example output JSON (not generated by a model):")
    print(json.dumps(example_model_output(), indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
